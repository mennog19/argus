// Regenerates src/ui/entry-icons/brands.generated.ts from src/assets/brand-icons.json.
//
// brand-icons.json is the source of truth: one { slug, domains } per brand,
// where slug is a Simple Icons slug (https://simpleicons.org). Only the brands
// listed there are baked into the app, so the bundle carries a few hundred
// logos at most rather than all of Simple Icons. Run `pnpm icons:brands`
// after editing the list.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const root = new URL("..", import.meta.url);
const list = JSON.parse(readFileSync(new URL("src/assets/brand-icons.json", root), "utf8"));
const bySlug = new Map(Object.values(simpleIcons).map((icon) => [icon.slug, icon]));

const seenDomains = new Map();
const brands = list.map(({ slug, domains }) => {
  const icon = bySlug.get(slug);
  if (!icon) {
    throw new Error(`Unknown Simple Icons slug "${slug}" (it may have been removed upstream).`);
  }
  for (const domain of domains) {
    if (seenDomains.has(domain)) {
      throw new Error(
        `Domain "${domain}" is listed for both ${seenDomains.get(domain)} and ${slug}.`,
      );
    }
    seenDomains.set(domain, slug);
  }
  return { slug, title: icon.title, hex: icon.hex, domains, path: icon.path };
});
brands.sort((a, b) => a.title.localeCompare(b.title));

const source = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Logos from Simple Icons (CC0 1.0, https://simpleicons.org). Brand names and
// logos are trademarks of their respective owners.
import type { BrandIconData } from "./brand-icons";

export const BRAND_ICON_DATA: readonly BrandIconData[] = ${JSON.stringify(brands, null, 2)};
`;

const target = fileURLToPath(new URL("src/ui/entry-icons/brands.generated.ts", root));
writeFileSync(target, source);
console.log(`Wrote ${brands.length} brands to ${target}`);
